import { describe, expect, it, vi } from 'vitest';
import { INBOX_NOW } from '../domain/leave/fixtures';
import { createDemoController } from './controller';
import { DEMO_COPY } from './copy';
import { DEMO_ACCOUNTS, DEMO_PASSWORD } from './session';
import { DEMO_STORAGE_KEY, loadDemoSnapshot } from './snapshot';
import { createBaselineState } from './state';
import { memoryStorage } from './test-support';

describe('T008 app-owned cross-persona integration', () => {
  it.each(['approve', 'reject'] as const)('carries the same LV-2026-102 to HR %s, persists, restores Dates and denies repeat decisions', decision => {
    const storage = memoryStorage();
    const owner = createDemoController(storage);
    expect(owner.getSnapshot().session).toBeNull();
    expect(owner.getSnapshot().login('hr-demo', DEMO_PASSWORD).ok).toBe(true);
    expect(owner.getSnapshot().hr?.requestId).toBeNull();
    owner.getSnapshot().logout();
    owner.getSnapshot().login('manager-demo', DEMO_PASSWORD);
    const initial = structuredClone(owner.getSnapshot().requests[1]);
    const manager = owner.getSnapshot().manager!;
    const approved = manager.onApprove('LV-2026-102', initial.version);
    expect(approved.ok).toBe(true);
    expect(owner.getSnapshot().requests[1].auditHistory).toHaveLength(initial.auditHistory.length + 1);
    owner.getSnapshot().logout();
    expect(owner.getSnapshot().requests).toBe(approved.ok ? approved.requests : null);
    const afterLogout = createDemoController(storage);
    expect(afterLogout.getSnapshot().session).toBeNull();
    afterLogout.getSnapshot().login('hr-demo', DEMO_PASSWORD);
    expect(afterLogout.getSnapshot().manager).toBeNull();
    expect(manager.onApprove('LV-2026-102', 1)).toEqual({ ok: false, error: 'unauthorized' });
    const hr = afterLogout.getSnapshot().hr!;
    expect(hr.requestId).toBe('LV-2026-102');
    expect(hr.requests[1].auditHistory.slice(0, initial.auditHistory.length)).toEqual(initial.auditHistory);
    expect(hr.requests.some(request => request.requestId === 'LV-2026-001')).toBe(false);
    const reason = 'ت'.repeat(500);
    const result = hr.onDecide('LV-2026-102', 1, decision, reason);
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.error);
    expect(result.request.auditHistory.at(-1)).toMatchObject({ actor: 'HR-1', actorRole: 'hr', timestamp: INBOX_NOW, eventType: 'decision' });
    expect(result.request.version).toBe(initial.version);
    expect(result.request.auditHistory).toHaveLength(initial.auditHistory.length + 2);
    if (decision === 'reject') expect(result.request.auditHistory.at(-1)?.details.reason).toBe(reason);
    expect(hr.onDecide('LV-2026-102', 1, decision, reason)).toEqual({ ok: false, error: 'invalid_state' });
    const restored = createDemoController(storage).getSnapshot();
    expect(restored.session).toEqual(DEMO_ACCOUNTS[1]);
    expect(restored.requests).toEqual(afterLogout.getSnapshot().requests);
    expect(restored.hr?.requestId).toBe('LV-2026-102');
  });
  it('guards role boundaries at the current session even for previously captured callbacks', () => {
    const owner = createDemoController(memoryStorage());
    owner.getSnapshot().login('manager-demo', DEMO_PASSWORD);
    const manager = owner.getSnapshot().manager!;
    manager.onApprove('LV-2026-102', 1);
    expect(owner.getSnapshot().login('hr-demo', DEMO_PASSWORD).ok).toBe(false);
    owner.getSnapshot().logout();
    owner.getSnapshot().login('hr-demo', DEMO_PASSWORD);
    expect(manager.onReject('LV-2026-101', 1, 'other', 'سبب')).toEqual({ ok: false, error: 'unauthorized' });
    expect(manager.onApprove('LV-2026-101', 1)).toEqual({ ok: false, error: 'unauthorized' });
    const hr = owner.getSnapshot().hr!;
    const before = structuredClone(hr.requests);
    expect(hr.onDecide('LV-2026-102', 2, 'approve')).toEqual({ ok: false, error: 'stale_version' });
    expect(hr.onDecide('LV-2026-102', 1, 'reject', ' ')).toEqual({ ok: false, error: 'reason_required' });
    expect(hr.onDecide('LV-2026-102', 1, 'reject', '😀'.repeat(501))).toEqual({ ok: false, error: 'reason_too_long' });
    expect(hr.onDecide('LV-2026-106', 1, 'approve')).toEqual({ ok: false, error: 'invalid_state' });
    expect(owner.getSnapshot().requests).toEqual(before);
    owner.getSnapshot().logout();
    expect(hr.onDecide('LV-2026-102', 1, 'approve')).toEqual({ ok: false, error: 'unauthorized' });
  });
  it('does not write or mutate for invalid login, no-op confirmation, unavailable navigation or cancelled reset', () => {
    const storage = memoryStorage();
    const owner = createDemoController(storage);
    const listener = vi.fn();
    const unsubscribe = owner.subscribe(listener);
    const initial = owner.getSnapshot();
    expect(owner.getSnapshot()).toBe(initial);
    owner.getSnapshot().login('MGR-2001', DEMO_PASSWORD);
    owner.getSnapshot().confirmReset();
    expect(storage.writes()).toBe(0);
    expect(owner.getSnapshot()).toBe(initial);
    owner.getSnapshot().login('manager-demo', DEMO_PASSWORD);
    owner.getSnapshot().manager!.onApprove('LV-2026-102', 1);
    const before = owner.getSnapshot();
    const saved = storage.values.get(DEMO_STORAGE_KEY);
    owner.getSnapshot().requestReset();
    owner.getSnapshot().cancelReset();
    expect(owner.getSnapshot().requests).toBe(before.requests);
    expect(owner.getSnapshot().session).toBe(before.session);
    expect(storage.values.get(DEMO_STORAGE_KEY)).toBe(saved);
    owner.getSnapshot().notifyUnavailable('dashboard');
    const first = owner.getSnapshot().toast.notice!;
    expect(first).toMatchObject({ title: DEMO_COPY.unavailableTitle, message: DEMO_COPY.unavailableMessage });
    owner.getSnapshot().notifyUnavailable('assistant');
    expect(owner.getSnapshot().toast.notice!.id).toBeGreaterThan(first.id);
    owner.getSnapshot().toast.onDismiss(first.id);
    expect(owner.getSnapshot().toast.notice).not.toBeNull();
    owner.getSnapshot().toast.onDismiss(owner.getSnapshot().toast.notice!.id);
    expect(owner.getSnapshot().toast.notice).toBeNull();
    owner.getSnapshot().notifyUnavailable('leave');
    owner.getSnapshot().notifyUnavailable('unknown');
    expect(owner.getSnapshot().toast.notice).toBeNull();
    expect(storage.values.get(DEMO_STORAGE_KEY)).toBe(saved);
    owner.getSnapshot().requestReset();
    owner.getSnapshot().confirmReset();
    expect(owner.getSnapshot()).toMatchObject(createBaselineState());
    expect(loadDemoSnapshot(storage).state).toEqual(createBaselineState());
    expect(listener).toHaveBeenCalled();
    unsubscribe();
    const count = listener.mock.calls.length;
    owner.getSnapshot().dismissRecovery();
    expect(listener).toHaveBeenCalledTimes(count);
  });
  it('recovers corrupt state to logged-out baseline and exposes a dismissible one-time notice', () => {
    const storage = memoryStorage(); storage.values.set(DEMO_STORAGE_KEY, 'broken');
    const owner = createDemoController(storage);
    expect(owner.getSnapshot()).toMatchObject(createBaselineState());
    expect(owner.getSnapshot().recoveryNotice).toBe(DEMO_COPY.recovery);
    owner.getSnapshot().dismissRecovery();
    expect(owner.getSnapshot().recoveryNotice).toBeNull();
    owner.getSnapshot().login('hr-demo', DEMO_PASSWORD);
    expect(createDemoController(storage).getSnapshot().recoveryNotice).toBeNull();
  });
  it('continues safely in memory on reads/writes failing, including logout and reset, with exact R1 disclosure', () => {
    const storage = { getItem: () => { throw new Error('blocked'); }, setItem: () => { throw new Error('quota'); }, removeItem: () => { throw new Error('blocked'); } };
    const owner = createDemoController(storage);
    expect(owner.getSnapshot().storageNotice).toBe(DEMO_COPY.storageUnavailable);
    expect(owner.getSnapshot().persistence).toBe('memory-only');
    owner.getSnapshot().login('manager-demo', DEMO_PASSWORD);
    expect(owner.getSnapshot().manager!.onApprove('LV-2026-102', 1).ok).toBe(true);
    owner.getSnapshot().logout();
    owner.getSnapshot().login('hr-demo', DEMO_PASSWORD);
    expect(owner.getSnapshot().hr?.requestId).toBe('LV-2026-102');
    expect(owner.getSnapshot().hr!.onDecide('LV-2026-102', 1, 'approve').ok).toBe(true);
    owner.getSnapshot().requestReset(); owner.getSnapshot().confirmReset();
    expect(owner.getSnapshot()).toMatchObject(createBaselineState());
    expect(owner.getSnapshot().storageNotice).toBe(DEMO_COPY.storageUnavailable);
  });
  it('keeps the memory-only disclosure when writes succeed but reads stay blocked', () => {
    const storage = memoryStorage();
    const owner = createDemoController({ ...storage, getItem: () => { throw new Error('blocked reads'); } });
    owner.getSnapshot().login('manager-demo', DEMO_PASSWORD);
    expect(owner.getSnapshot().manager!.onApprove('LV-2026-102', 1).ok).toBe(true);
    owner.getSnapshot().logout();
    owner.getSnapshot().login('hr-demo', DEMO_PASSWORD);
    expect(owner.getSnapshot().hr?.requestId).toBe('LV-2026-102');
    expect(owner.getSnapshot().persistence).toBe('memory-only');
    expect(owner.getSnapshot().storageNotice).toBe(DEMO_COPY.storageUnavailable);
    expect(storage.values.has(DEMO_STORAGE_KEY)).toBe(false);
  });
  it('changes from available to memory-only on write failure without reporting a false save', () => {
    const storage = memoryStorage();
    const owner = createDemoController({ ...storage, setItem: () => { throw new Error('quota'); } });
    expect(owner.getSnapshot().storageNotice).toBeNull();
    owner.getSnapshot().login('hr-demo', DEMO_PASSWORD);
    expect(owner.getSnapshot().persistence).toBe('memory-only');
    expect(owner.getSnapshot().storageNotice).toBe(DEMO_COPY.storageUnavailable);
    expect(loadDemoSnapshot(storage).state.session).toBeNull();
  });
});
